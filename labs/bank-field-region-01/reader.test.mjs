import assert from "node:assert/strict";
import {FIELDS,PROMPT,RESPONSE_SCHEMA,validate,planRead2,mergeRead2} from "./reader.mjs";
const clone=x=>JSON.parse(JSON.stringify(x));
const blank=()=>({state:"missing",literal:null,box:null});
const fixture={kind:"receipt",selection:"single",direction:"unsigned",fields:Object.fromEntries(FIELDS.map(k=>[k,blank()]))};
fixture.fields.amount={state:"clear",literal:"123.456 VNĐ",box:[1,2,30,40]};
fixture.fields.recipient_account={state:"unclear",literal:"123999?",box:[20,10,30,90]};
fixture.fields.time={state:"unclear",literal:null,box:null};
const a=validate(fixture,FIELDS);assert.equal(planRead2(a,FIELDS).mode,"full_image");
const b=clone(a);b.fields.time.box=[30,10,40,60];assert.equal(planRead2(b,FIELDS).mode,"crop");
const c=clone(a);c.fields.recipient_account={state:"clear",literal:"1239999",box:[20,10,30,90]};c.fields.time={state:"clear",literal:"12:03",box:null};
assert.equal(mergeRead2(a,c,["recipient_account","time"],FIELDS).result.fields.time.literal,"12:03");
assert.equal(mergeRead2(a,c,["recipient_account"],FIELDS).result.fields.time.literal,null);
c.fields.amount.literal="123.457 VNĐ";assert.equal(mergeRead2(a,c,["recipient_account"],FIELDS).conflict,true);
const d=clone(a);d.selection="ambiguous";assert.equal(planRead2(d,FIELDS).mode,"review");d.selection="single";d.kind="non_bill";assert.equal(planRead2(d,FIELDS).mode,"review");
const e=clone(a);e.fields.time=blank();e.fields.recipient_account=blank();assert.equal(planRead2(e,FIELDS).mode,"stop");
const g=clone(a);g.fields.amount.box=[50,1,2,3];assert.equal(validate(g,FIELDS).fields.amount.box,null);
const h=clone(a);h.fields.time={state:"clear",literal:null,box:null};assert.throws(()=>validate(h,FIELDS),/clear_without_text/);
assert(!PROMPT.includes("2901181999999")&&!PROMPT.includes("BUI XUAN TUNG"));assert(RESPONSE_SCHEMA.required.includes("fields"));
console.log("12 first-pass / second-pass planner assertions passed.");
