-- BANK-162: Agribank Plus OTT app notifications, independent from SMS and accounting.
begin;
create table if not exists public.taphoa_agribank_notifications (
 id bigint generated by default as identity primary key,
 device_id uuid not null references public.taphoa_sms_ingest_devices(id),
 package_name text not null check (package_name='com.vnpay.Agribank3g'),
 title text not null default '',
 body text not null,
 posted_at timestamptz not null,
 fingerprint text not null,
 amount_vnd bigint,
 status text not null default 'unclassified',
 received_at timestamptz not null default now(),
 created_at timestamptz not null default now(),
 constraint agribank_notification_fingerprint unique(device_id,fingerprint),
 constraint agribank_notification_positive_amount check(amount_vnd is null or amount_vnd > 0)
);
create index if not exists agribank_notification_credit_recent_idx
 on public.taphoa_agribank_notifications(posted_at desc)
 where status='credit_candidate';
alter table public.taphoa_agribank_notifications enable row level security;
revoke all on public.taphoa_agribank_notifications from public,anon,authenticated;
commit;